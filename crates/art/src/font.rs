/// Zeichen der Zierschrift (Kleinbuchstaben werden zu Versalien, ß zu SS)
pub const DISPLAY_CHARS: &str = "ABCDEFGHIJKLMNOPQRSTUVWXYZÄÖÜ0123456789.,·:-'!?()";

fn seg_dist(px: f32, py: f32, a: (f32, f32), b: (f32, f32)) -> (f32, f32) {
    let (vx, vy) = (b.0 - a.0, b.1 - a.1);
    let l2 = vx * vx + vy * vy;
    let t = if l2 < 1e-6 { 0.0 } else { (((px - a.0) * vx + (py - a.1) * vy) / l2).clamp(0.0, 1.0) };
    let (qx, qy) = (a.0 + vx * t, a.1 + vy * t);
    (((px - qx).powi(2) + (py - qy).powi(2)).sqrt(), t)
}

/// Eine Versalie der Zierschrift im Maßstab `k` (Versalhöhe 14·k px): Breitfeder (senkrecht
/// kräftig, waagrecht fein), Keilserifen an den Stämmen, Fase (oben links hell), dunkler Rand.
/// Graustufen (weiß = hell), damit sie beim Zeichnen eingefärbt werden kann. Rückgabe: Leinwand,
/// Vorschub (px) und die Höhe der Oberkante der Versalien in der Leinwand.
pub fn display_glyph(ch: char, k: f32) -> Option<(Canvas, i32, i32)> {
    let (w, strokes) = dstrokes(ch)?;
    let pad = (2.0 * k).ceil() as i32 + 2;
    let top = (4.6 * k).ceil() as i32 + pad;
    let (cw, chh) = ((w * k).ceil() as i32 + pad * 2, top + (16.4 * k).ceil() as i32 + pad);
    let thick = 2.05 * k;
    let thin = 0.55 * k;
    // Serifen: kurze, sich verjüngende Querstriche an den Enden der Stämme
    let mut segs: Vec<((f32, f32), (f32, f32), bool)> = vec![];
    for (stem, pts) in &strokes {
        for i in 0..pts.len().saturating_sub(1) {
            segs.push((pts[i], pts[i + 1], false));
        }
        if *stem {
            for &e in [pts[0], pts[pts.len() - 1]].iter() {
                if e.1 <= 0.01 || e.1 >= 13.99 {
                    let len = 1.9;
                    segs.push(((e.0 - len, e.1), (e.0 + len, e.1), true));
                }
            }
        }
    }
    let mut c = Canvas::new(cw, chh);
    c.standing = false;
    // Abstand und Stärke je Pixel
    let mut cov = vec![0.0f32; (cw * chh) as usize];
    for y in 0..chh {
        for x in 0..cw {
            let gx = (x as f32 + 0.5 - pad as f32) / k;
            let gy = (y as f32 + 0.5 - top as f32) / k;
            let mut best = 0.0f32;
            for &(a, b, serif) in &segs {
                let (d, t) = seg_dist(gx, gy, a, b);
                let (vx, vy) = (b.0 - a.0, b.1 - a.1);
                let l = (vx * vx + vy * vy).sqrt().max(1e-4);
                // Breitfeder, nach rechts oben gekippt (wie römische Kapitale): senkrecht und „\“
                // kräftig, waagrecht und „/“ fein
                let ang = vy.atan2(vx);
                let pen = (ang + 0.35).sin().abs();
                let mut wd = if l < 0.05 { thick * 0.8 } else { thin + (thick - thin) * pen };
                if serif {
                    // Keil: zur Spitze hin dünner, am Stamm gekehlt
                    wd = thin * 1.5 + (thick - thin * 1.5) * 0.45 * (1.0 - (t - 0.5).abs() * 2.0).powf(1.5);
                }
                let half = wd * 0.5 / k;
                let v = ((half - d) * k + 0.5).clamp(0.0, 1.0);
                best = best.max(v);
            }
            cov[(y * cw + x) as usize] = best;
        }
    }
    for y in 0..chh {
        for x in 0..cw {
            let v = cov[(y * cw + x) as usize];
            if v < 0.35 {
                continue;
            }
            // Fase: oben links hell, unten rechts dunkel (Nachbarn ohne Deckung)
            let at = |xx: i32, yy: i32| if xx < 0 || yy < 0 || xx >= cw || yy >= chh { 0.0 } else { cov[(yy * cw + xx) as usize] };
            let edge_tl = 1.0 - at(x - 1, y - 1).min(at(x, y - 1));
            let edge_br = 1.0 - at(x + 1, y + 1).min(at(x, y + 1));
            let gy = (y - top) as f32 / (14.0 * k);
            let mut l = 0.92 - gy * 0.22 + edge_tl * 0.12 - edge_br * 0.28;
            l = l.clamp(0.3, 1.0);
            let g = (l * 255.0) as u8;
            c.set(x, y, [g, g, g, 255]);
        }
    }
    c.outline(true, 1.0);
    Some((c, (w * k + 2.4 * k).round() as i32, top))
}
