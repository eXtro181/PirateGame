/// Glyph-Leinwand (weiß) und Breite.
pub fn glyph(ch: char) -> Option<(Canvas, i32)> {
    let rows = GLYPHS.iter().find(|g| g.0 == ch)?.1;
    let (mut minc, mut maxc) = (5, -1);
    for m in rows.iter() {
        for c in 0..5 {
            if m & (16 >> c) != 0 {
                minc = minc.min(c);
                maxc = maxc.max(c);
            }
        }
    }
    if maxc < 0 {
        return None;
    }
    let w = maxc - minc + 1;
    let mut cv = Canvas::new(w, 8);
    cv.standing = false;
    for (y, m) in rows.iter().enumerate() {
        for c in minc..=maxc {
            if m & (16 >> c) != 0 {
                cv.set(c - minc, y as i32, hex(0xFFFFFF));
            }
        }
    }
    Some((cv, w))
}

